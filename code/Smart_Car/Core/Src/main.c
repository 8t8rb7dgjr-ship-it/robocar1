void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
    // 判断是不是蓝牙所在的串口触发了中断
    if(huart->Instance == USART3) {
        
        switch(rx_data) {
            case 'W': Car_Forward(600); break;     // 前进
            case 'S': Car_Backward(600); break;    // 后退
            
            case 'A': Car_StrafeLeft(500); break;  // 向左平移
            case 'D': Car_StrafeRight(500); break; // 向右平移
            
            case 'Q': Car_LeftCircle(500); break;  // 原地左转
            case 'E': Car_RightCircle(500); break; // 原地右转

            case 'w': Car_TurnLeftF(600); break;   // 向前左转
            case 's': Car_TurnRightF(600); break;  // 向前右转
            case 'a': Car_TurnLeftB(600); break;   // 向后左转
            case 'd': Car_TurnRightB(600); break;  // 向后右转

            case '1': Car_Forward(300); break;     // 慢速前进
            case '2': Car_Backward(300); break;    // 慢速倒车
            case '3': Car_LeftCircle(300); break;  // 原地左转微调
            case '4': Car_RightCircle(300); break; // 原地右转微调

            case 'X': 
            case ' ': Car_Stop(); break;           // 'X' 或 空格 键刹车
            
            default: break;
        }
        
        //必须重新开启中断
        HAL_UART_Receive_IT(&huart3, &rx_data, 1);
    }
}
